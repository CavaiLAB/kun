using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kun.Plugin.Sdk.Generators;

/// <summary>为显式 KunJob 能力生成静态调度声明。</summary>
[Generator(LanguageNames.CSharp)]
public sealed class JobGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Invalid = new("KUNSDK003", "作业声明无效", "{0}", "KunSdk", DiagnosticSeverity.Error, true);
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var jobs = context.SyntaxProvider.ForAttributeWithMetadataName("Kun.Plugin.Sdk.KunJobAttribute", static (_, _) => true,
            static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol).Collect();
        context.RegisterSourceOutput(jobs, static (output, values) =>
        {
            foreach (var type in values)
            {
                var job = type.GetAttributes().Single(a => a.AttributeClass?.ToDisplayString() == "Kun.Plugin.Sdk.KunJobAttribute");
                var code = job.ConstructorArguments[0].Value as string;
                var capability = type.GetAttributes().SingleOrDefault(a => a.AttributeClass?.ToDisplayString() == "Kun.Plugin.Sdk.CapabilityAttribute");
                if (code is null || code.Length > 100 || !System.Text.RegularExpressions.Regex.IsMatch(code, "^[a-z][a-z0-9-]*$", System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1)) ||
                    capability is null || type.ContainingType is not null || type.IsGenericType ||
                    type.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is not TypeDeclarationSyntax syntax || !syntax.Modifiers.Any(SyntaxKind.PartialKeyword)) ||
                    type.GetMembers("KunJobCode").Length != 0)
                { output.ReportDiagnostic(Diagnostic.Create(Invalid, type.Locations.FirstOrDefault(), "KunJob 必须标注顶层非泛型 partial Capability 请求，code 使用小写短横线名称。")); continue; }
                var response = capability.ConstructorArguments[1].Value as INamedTypeSymbol;
                if (response is null) continue; // CapabilityGenerator 报告完整诊断。
                var kind = type.IsRecord ? (type.TypeKind == TypeKind.Struct ? "record struct" : "record") : (type.TypeKind == TypeKind.Struct ? "struct" : "class");
                var ns = type.ContainingNamespace.IsGlobalNamespace ? "" : "namespace " + type.ContainingNamespace.ToDisplayString() + ";\n";
                var source = "// <auto-generated/>\n#nullable enable\n" + ns + "partial " + kind + " @" + type.Name + " : global::Kun.Plugin.Sdk.IJobRequest<" + response.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ">\n{\n    public static string KunJobCode => \"" + code + "\";\n}\n";
                output.AddSource(type.ToDisplayString().Replace("@", "").Replace('.', '_') + ".Job.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }
}
